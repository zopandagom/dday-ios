/// 음력 한 해의 각 달 1일.
struct LunarYearMonthStarts {
  let year: Int
  /// 음력 1월 1일의 양력 날짜 yyyymmdd
  let newYear: Int
  /// 윤달이 붙는 달. 0 이면 윤달 없음
  let leapMonth: Int
  /// 달 순서(윤달은 같은 번호 평달 바로 뒤)대로, 음력 1월 1일부터 그 달 1일까지의 일수
  let monthStartOffsets: [Int]

  init(_ year: Int, _ newYear: Int, leap leapMonth: Int, _ monthStartOffsets: [Int]) {
    self.year = year
    self.newYear = newYear
    self.leapMonth = leapMonth
    self.monthStartOffsets = monthStartOffsets
  }
}

